import { readFile, writeFile, mkdir, access } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import StyleDictionary from 'style-dictionary';

const ROOT = dirname(fileURLToPath(import.meta.url));
const PACKS = join(ROOT, '..', 'platform', 'src', 'countries', 'index.mjs');
const FLUTTER = join(ROOT, 'flutter', 'myca_design', 'lib', 'src');
const BANNER = 'Generated by design/build.mjs from design/tokens and the country packs. Do not edit.';
const FACT_KEYS = ['code', 'name', 'status', 'currency', 'symbol', 'locale', 'languages', 'minorUnit', 'yearStartMonth', 'yearStartDay', 'yearLabel', 'taxId', 'taxName'];

export async function loadTokens() {
  const sd = new StyleDictionary({
    source: [join(ROOT, 'tokens', '**', '*.json')],
    log: { verbosity: 'silent', warnings: 'disabled' },
    platforms: { raw: { transforms: ['name/camel'] } },
  });
  const dictionary = await sd.getPlatformTokens('raw');
  return dictionary.allTokens.map((token) => ({
    path: token.path,
    type: token.$type ?? token.type,
    value: token.$value ?? token.value,
    description: token.$description ?? token.comment ?? '',
  }));
}

export function factsFromPacks(packs, snapshot) {
  const out = {};
  for (const pack of packs) {
    const fact = {};
    for (const key of FACT_KEYS) {
      if (pack[key] !== undefined) fact[key] = Array.isArray(pack[key]) ? [...pack[key]] : pack[key];
    }
    const fallback = snapshot?.countries?.[pack.code] ?? {};
    fact.languages ??= fallback.languages ?? [pack.locale.split('-')[0]];
    fact.taxName ??= fallback.taxName ?? pack.taxId;
    fact.app = { flavor: pack.app.flavor, label: pack.app.label, edition: pack.app.edition };
    out[pack.code] = fact;
  }
  for (const [code, fact] of Object.entries(snapshot?.countries ?? {})) {
    if (!out[code]) out[code] = fact;
  }
  return out;
}

export async function loadFacts() {
  const snapshot = JSON.parse(await readFile(join(ROOT, 'country-facts.json'), 'utf8'));
  const havePacks = await access(PACKS).then(() => true, () => false);
  if (!havePacks) return { facts: snapshot.countries, fromPacks: false, snapshot };
  const { PACKS: packs } = await import(pathToFileURL(PACKS).href);
  return { facts: factsFromPacks(packs, snapshot), fromPacks: true, snapshot };
}

const kebab = (path) => path.join('-').replace(/([a-z])([A-Z])/g, '$1-$2').toLowerCase();
const camel = (path) => path.map((part, i) => {
  const clean = String(part).replace(/[^A-Za-z0-9]/g, '');
  return i === 0 ? clean : clean.charAt(0).toUpperCase() + clean.slice(1);
}).join('').replace(/^(\d)/, 'n$1');

function cssValue(token) {
  const { type, value } = token;
  if (type === 'fontFamily') return value.map((name) => (/\s/.test(name) && !name.includes('-apple') ? `'${name}'` : name)).join(', ');
  if (type === 'cubicBezier') return `cubic-bezier(${value.join(', ')})`;
  if (type === 'shadow') return value.map((s) => `${s.offsetX} ${s.offsetY} ${s.blur} ${s.spread} ${s.color}`).join(', ');
  return String(value);
}

function themeVars(tokens, scheme) {
  return tokens
    .filter((t) => t.path[0] === 'theme' && t.path[1] === scheme)
    .map((t) => `  --${kebab(t.path.slice(2))}: ${t.value};`);
}

function countryVars(tokens, code, dark) {
  const pick = (name) => tokens.find((t) => t.path[0] === 'country' && t.path[1] === code && t.path[2] === name)?.value;
  return [
    `  --accent: ${pick(dark ? 'accentDark' : 'accent')};`,
    `  --accent-soft: ${pick(dark ? 'accentSoftDark' : 'accentSoft')};`,
    `  --highlight: ${pick('highlight')};`,
  ];
}

export function renderCss(tokens, facts) {
  const base = tokens
    .filter((t) => !['theme', 'country'].includes(t.path[0]))
    .map((t) => `  --${kebab(t.path)}: ${cssValue(t)};`);
  const codes = Object.keys(facts).map((code) => code.toLowerCase());
  const lines = [`/* ${BANNER} */`, ':root {', ...base, ...themeVars(tokens, 'light'), ...countryVars(tokens, 'in', false), '  color-scheme: light;', '}', ''];
  for (const code of codes) lines.push(`[data-country="${code}"] {`, ...countryVars(tokens, code, false), '}', '');
  const dark = [...themeVars(tokens, 'dark'), '  color-scheme: dark;'];
  lines.push('[data-theme="dark"] {', ...dark, ...countryVars(tokens, 'in', true), '}', '');
  for (const code of codes) lines.push(`[data-theme="dark"][data-country="${code}"], [data-theme="dark"] [data-country="${code}"] {`, ...countryVars(tokens, code, true), '}', '');
  lines.push('@media (prefers-color-scheme: dark) {', '  :root:not([data-theme="light"]) {', ...dark.map((l) => `  ${l}`), ...countryVars(tokens, 'in', true).map((l) => `  ${l}`), '  }');
  for (const code of codes) lines.push(`  :root:not([data-theme="light"])[data-country="${code}"], :root:not([data-theme="light"]) [data-country="${code}"]:not([data-theme="light"]) {`, ...countryVars(tokens, code, true).map((l) => `  ${l}`), '  }');
  lines.push('}', '');
  lines.push(':root, [data-country] { font-family: var(--font-family-brand); }');
  lines.push(':lang(ar) { font-family: var(--font-family-arabic); }');
  lines.push(':lang(hi) { font-family: var(--font-family-devanagari); }');
  lines.push('.money, .num { font-variant-numeric: tabular-nums; }', '');
  return lines.join('\n');
}

function nest(tokens) {
  const tree = {};
  for (const t of tokens) {
    let node = tree;
    t.path.slice(0, -1).forEach((part) => { node = node[part] ??= {}; });
    node[t.path.at(-1)] = t.type === 'dimension' && /px$/.test(t.value) ? Number(t.value.slice(0, -2)) : t.type === 'duration' ? Number(String(t.value).replace('ms', '')) : t.value;
  }
  return tree;
}

export function renderJs(tokens, facts) {
  return [
    `// ${BANNER}`,
    `export const TOKENS = Object.freeze(${JSON.stringify(nest(tokens), null, 2)});`,
    '',
    `export const COUNTRIES = Object.freeze(${JSON.stringify(facts, null, 2)});`,
    '',
  ].join('\n');
}

const dartColor = (hex) => {
  const h = hex.replace('#', '').toUpperCase();
  return h.length === 8 ? `Color(0x${h.slice(6)}${h.slice(0, 6)})` : `Color(0xFF${h})`;
};
const dartString = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$')}'`;
const px = (v) => Number(String(v).replace(/px$/, ''));

export function renderDart(tokens, facts) {
  const out = [`// ${BANNER}`, '// ignore_for_file: constant_identifier_names', '', "import 'package:flutter/material.dart';", ''];
  const group = (name, filter, render) => {
    out.push(`abstract final class ${name} {`);
    for (const t of tokens.filter(filter)) {
      if (t.description) out.push(`  /// ${t.description}`);
      out.push(`  static const ${render(t)};`);
    }
    out.push('}', '');
  };
  group('MycaColors', (t) => t.path[0] === 'color', (t) => `${camel(t.path.slice(1))} = ${dartColor(t.value)}`);
  group('MycaSpace', (t) => t.path[0] === 'space', (t) => `s${t.path[1]} = ${px(t.value).toFixed(1)}`);
  group('MycaRadius', (t) => t.path[0] === 'radius', (t) => `${camel(t.path.slice(1))} = ${px(t.value).toFixed(1)}`);
  group('MycaSize', (t) => t.path[0] === 'size', (t) => `${camel(t.path.slice(1))} = ${px(t.value).toFixed(1)}`);
  group('MycaMotion', (t) => t.path[0] === 'motion', (t) => t.type === 'duration'
    ? `${camel(t.path.slice(2))} = Duration(milliseconds: ${String(t.value).replace('ms', '')})`
    : `${camel(t.path.slice(2))}Curve = Cubic(${t.value.join(', ')})`);
  const fonts = tokens.filter((t) => t.path[0] === 'font' && t.path[1] === 'family');
  out.push('abstract final class MycaFonts {');
  for (const t of fonts) out.push(`  static const ${camel(t.path.slice(2))} = ${dartString(t.value[0])};`);
  out.push('}', '');
  const styles = [...new Set(tokens.filter((t) => t.path[0] === 'type').map((t) => t.path[1]))];
  out.push('class MycaTypeStep {', '  const MycaTypeStep(this.size, this.weight, this.tracking, this.leading);', '', '  final double size;', '  final FontWeight weight;', '  final double tracking;', '  final double leading;', '}', '');
  out.push('abstract final class MycaType {');
  for (const name of styles) {
    const get = (k) => tokens.find((t) => t.path[0] === 'type' && t.path[1] === name && t.path[2] === k).value;
    out.push(`  static const ${name} = MycaTypeStep(${px(get('size'))}, FontWeight.w${get('weight')}, ${px(get('tracking'))}, ${get('leading')});`);
  }
  out.push('}', '');
  out.push('class MycaSurfaceColors {');
  const roles = tokens.filter((t) => t.path[0] === 'theme' && t.path[1] === 'light').map((t) => t.path[2]);
  out.push(`  const MycaSurfaceColors({${roles.map((r) => `required this.${r}`).join(', ')}});`, '');
  for (const r of roles) out.push(`  final Color ${r};`);
  out.push('');
  for (const scheme of ['light', 'dark']) {
    const args = roles.map((r) => `${r}: ${dartColor(tokens.find((t) => t.path[0] === 'theme' && t.path[1] === scheme && t.path[2] === r).value)}`);
    out.push(`  static const ${scheme} = MycaSurfaceColors(${args.join(', ')});`);
  }
  out.push('}', '');
  out.push('class MycaCountryLook {', '  const MycaCountryLook({required this.accent, required this.accentSoft, required this.accentDark, required this.accentSoftDark, required this.highlight});', '', '  final Color accent;', '  final Color accentSoft;', '  final Color accentDark;', '  final Color accentSoftDark;', '  final Color highlight;', '}', '');
  out.push('const mycaCountryLooks = <String, MycaCountryLook>{');
  for (const code of Object.keys(facts)) {
    const pick = (name) => tokens.find((t) => t.path[0] === 'country' && t.path[1] === code.toLowerCase() && t.path[2] === name)?.value;
    if (!pick('accent')) continue;
    out.push(`  '${code}': MycaCountryLook(accent: ${dartColor(pick('accent'))}, accentSoft: ${dartColor(pick('accentSoft'))}, accentDark: ${dartColor(pick('accentDark'))}, accentSoftDark: ${dartColor(pick('accentSoftDark'))}, highlight: ${dartColor(pick('highlight'))}),`);
  }
  out.push('};', '');
  out.push('class MycaCountryFacts {');
  out.push('  const MycaCountryFacts({required this.code, required this.name, required this.status, required this.currency, required this.symbol, required this.locale, required this.languages, required this.minorUnit, required this.yearStartMonth, required this.yearStartDay, required this.yearLabel, required this.taxId, required this.taxName, required this.flavor, required this.appLabel});', '');
  for (const [k, t] of [['code', 'String'], ['name', 'String'], ['status', 'String'], ['currency', 'String'], ['symbol', 'String'], ['locale', 'String'], ['languages', 'List<String>'], ['minorUnit', 'String'], ['yearStartMonth', 'int'], ['yearStartDay', 'int'], ['yearLabel', 'String'], ['taxId', 'String'], ['taxName', 'String'], ['flavor', 'String'], ['appLabel', 'String']]) out.push(`  final ${t} ${k};`);
  out.push('}', '');
  out.push('const mycaCountryFacts = <String, MycaCountryFacts>{');
  for (const [code, f] of Object.entries(facts)) {
    out.push(`  '${code}': MycaCountryFacts(code: '${code}', name: ${dartString(f.name)}, status: ${dartString(f.status)}, currency: '${f.currency}', symbol: ${dartString(f.symbol)}, locale: '${f.locale}', languages: [${f.languages.map(dartString).join(', ')}], minorUnit: ${dartString(f.minorUnit)}, yearStartMonth: ${f.yearStartMonth}, yearStartDay: ${f.yearStartDay}, yearLabel: ${dartString(f.yearLabel)}, taxId: ${dartString(f.taxId)}, taxName: ${dartString(f.taxName)}, flavor: ${dartString(f.app.flavor)}, appLabel: ${dartString(f.app.label)}),`);
  }
  out.push('};', '');
  return out.join('\n');
}

export async function renderAll() {
  const tokens = await loadTokens();
  const { facts, fromPacks, snapshot } = await loadFacts();
  return {
    fromPacks,
    snapshot: { ...snapshot, countries: facts },
    files: {
      [join(ROOT, 'generated', 'css', 'myca.css')]: renderCss(tokens, facts),
      [join(ROOT, 'generated', 'js', 'tokens.mjs')]: renderJs(tokens, facts),
      [join(FLUTTER, 'tokens.g.dart')]: renderDart(tokens, facts),
    },
  };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { files, fromPacks, snapshot } = await renderAll();
  for (const [path, body] of Object.entries(files)) {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, body);
  }
  if (fromPacks) await writeFile(join(ROOT, 'country-facts.json'), `${JSON.stringify(snapshot, null, 2)}\n`);
  console.log(`Wrote ${Object.keys(files).length} files; country facts from ${fromPacks ? 'platform/src/countries' : 'the checked-in snapshot'}.`);
}
