import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createState } from '../src/store.mjs';
import { runTool } from '../src/tools.mjs';
import { chat } from '../src/router.mjs';
import { localToday } from '../src/dates.mjs';

test('the GSTR-9 draft adds the year\'s months: outward supplies, credit availed and reversed, tax paid, and the HSN summary', async () => {
  const state = createState();
  state.company = { ...state.company, name: 'Asha Traders', gstin: '27AABCU9603R1ZN', state: '27' };
  await runTool(state, 'create_invoice', { partyName: 'Kiran Stores', partyGstin: '27AAACK1234F1Z5', lines: [{ description: 'Consulting', hsn: '9983', qty: 1, rate: 100000, gstRate: 18 }], date: '2026-05-05' });
  await runTool(state, 'create_invoice', { partyName: 'Walk-in', lines: [{ description: 'Cloth', hsn: '5208', qty: 10, rate: 1000, gstRate: 5 }], date: '2026-06-05' });
  await runTool(state, 'create_credit_note', { invoiceId: 'INV-0002', amount: 1050, reason: 'returned', date: '2026-06-20' });
  const bill = await runTool(state, 'create_purchase', { partyName: 'Fabric Co', partyGstin: '27AAACF7856R1ZY', lines: [{ description: 'Cloth', hsn: '5208', qty: 1, rate: 40000, gstRate: 5 }], date: '2026-05-10', supplierInvoiceNo: 'FC/1' });
  await runTool(state, 'create_purchase_note', { billId: bill.invoice.id, amount: 2100, reason: 'short', date: '2026-05-20' });
  await runTool(state, 'record_gst_payment', { period: '2026-05', date: '2026-06-15', cpin: '26050012345678' });
  await runTool(state, 'record_filing', { returnType: 'GSTR-3B', period: '2026-05', arn: 'AA270526123456', filedOn: '2026-06-18' });
  const out = await runTool(state, 'gstr9_draft', { fy: '2026-27' });
  assert.equal(out.ok, true, JSON.stringify(out));
  const d = out.data;
  assert.equal(d.fy, '2026-27');
  const [year, month] = localToday().slice(0, 7).split('-').map(Number);
  const monthsSoFar = Math.max(0, Math.min(12, (year - 2026) * 12 + month - 3));
  assert.equal(d.months.length, monthsSoFar, 'April 2026 to this month, at most the twelve months of the year');
  assert.equal(d.table4.b2bInvoices, 1);
  assert.equal(d.table4.b2cInvoices, 1);
  assert.equal(d.table4.outwardTaxable, 110000);
  assert.equal(d.table4.outwardTax.total, 18500);
  assert.equal(d.table4.creditNotes.taxable, 1000);
  assert.equal(d.table4.netTaxable, 109000);
  assert.equal(d.table6.itcAvailed.total, 2000);
  assert.equal(d.table6.purchases, 1);
  assert.equal(d.table7.reversed.total, 100);
  assert.equal(d.table9.monthsRecorded, 1);
  assert.equal(d.table9.paidInCash.total, 16100);
  assert.equal(d.table9.paidByCredit, 1900);
  assert.deepEqual(d.table17.map((row) => [row.hsn, row.ratePercent, row.taxable]), [['5208', 5, 10000], ['9983', 18, 100000]]);
  assert.match(d.notes.join(' '), /missing: 2026-06/);
  assert.match(d.notes.join(' '), /GSTR-3B is not recorded as filed for 2026-06/);
  assert.match(d.notes.join(' '), /Table 5/);
  const reply = await chat(state, 'gstr-9 for 2026-27');
  assert.match(reply.reply, /GSTR-9 draft for 2026-27/);
  assert.match(reply.reply, /Outward supplies: taxable ₹1,10,000\.00 on 2 invoices \(1 B2B\), tax ₹18,500\.00; credit notes ₹1,000\.00/);
  assert.match(reply.reply, /Tax paid: ₹16,100\.00 in cash and ₹1,900\.00 by credit over 1 recorded months/);
  assert.equal((await runTool(state, 'gstr9_draft', { fy: '202627' })).error, 'BAD_FY');
});
