const acc = (state, code) => listAccounts(state.ledger).find((a) => a.code === code);
const balance = (state, code) => { const a = acc(state, code); return a ? Math.round((a.creditsPosted - a.debitsPosted) * 100) / 100 : 0; };

async function books() {
  const state = createState();
  state.company = { ...state.company, name: 'Asha Traders', gstin: '27AABCU9603R1ZN', state: '27', tdsDeductor: true, tan: 'MUMA12345B' };
  const add = async (args) => { const out = await runTool(state, 'add_employee', args); assert.equal(out.ok, true, JSON.stringify(out)); return out.employee; };
  await add({ name: 'Ravi Kumar', joinedOn: '2026-04-01', components: [{ name: 'Basic', amount: 20000 }, { name: 'HRA', amount: 10000 }], pfMember: true, esiMember: true, ptState: '27', pan: 'ABCPK1234L', sex: 'male' });
  await add({ name: 'Meena Shah', joinedOn: '2026-10-16', components: [{ name: 'Salary', amount: 18000 }], pfMember: true, esiMember: true, ptState: '27', sex: 'female', taxRegime: 'new' });
  await add({ name: 'Arjun Rao', joinedOn: '2026-04-01', components: [{ name: 'Basic', amount: 100000 }, { name: 'HRA', amount: 50000 }], ptState: '27', sex: 'male', taxRegime: 'new', pan: 'ABCPR1234L' });
  return state;
}

test('the monthly run applies PF, ESI, professional tax and salary TDS from the dated rules, prorated for a joiner', async () => {
  const state = await books();
  const out = await runTool(state, 'payroll_run', { period: '2026-10' });
  assert.equal(out.ok, true, JSON.stringify(out));
  const d = out.data;
  assert.equal(d.month, 'October 2026');
  assert.equal(d.status, 'draft');
  assert.equal(d.employees, 3);
  const ravi = d.rows.find((row) => row.name === 'Ravi Kumar');
  assert.equal(ravi.gross, 30000);
  assert.equal(ravi.pfWages, 15000, 'basic above the ceiling is capped');
  assert.equal(ravi.pfEmployee, 1800);
  assert.equal(ravi.eps, 1249.5);
  assert.equal(ravi.pfEmployer, 550.5);
  assert.equal(ravi.edli, 75);
  assert.equal(ravi.esiEmployee, 0);
  assert.match(ravi.notes.join(' '), /above the state insurance wage limit/);
  assert.equal(ravi.pt, 200);
  assert.equal(ravi.tds, 0, 'three lakh sixty a year is under the rebate limit');
  assert.equal(ravi.net, 30000 - 1800 - 200);
  const meena = d.rows.find((row) => row.name === 'Meena Shah');
  assert.equal(meena.daysWorked, 16);
  assert.equal(meena.gross, 9290.32);
  assert.equal(meena.pfWages, 9290.32, 'no Basic part, so the whole pay counts');
  assert.match(meena.notes.join(' '), /whole pay is taken as provident fund wages/);
  assert.equal(meena.esiEmployee, 69.68);
  assert.equal(meena.esiEmployer, 301.94);
  assert.equal(meena.pt, 0, 'a woman earning under the limit pays no professional tax in Maharashtra');
  const arjun = d.rows.find((row) => row.name === 'Arjun Rao');
  assert.equal(arjun.pfEmployee, 0);
  assert.equal(arjun.pt, 200);
  const annual = incomeTax.computeIncomeTax({ fy: '2026-27', regime: 'new', salaryPaise: 150000 * 12 * 100, residentIndividual: true }).taxPayablePaise / 100;
  assert.ok(annual > 100000, `annual tax ${annual}`);
  assert.equal(arjun.tdsBasis.annualTax, annual);
  assert.equal(arjun.tdsBasis.projectedSalary, 1800000, 'April to September are taken at this month\'s pay');
  assert.equal(arjun.tds, Math.round(annual / 6), 'spread over the six months left in the year');
  assert.equal(arjun.net, 150000 - 200 - arjun.tds);
  assert.equal(d.totals.pfAdmin, 500, 'the administrative charge has a monthly minimum');
  assert.equal(d.totals.employerContributions, Math.round((d.totals.pfEmployer + d.totals.eps + d.totals.edli + 500 + d.totals.esiEmployer) * 100) / 100);
  assert.equal(d.unreviewed, true);
  assert.match(d.notes.join(' '), /not reviewed yet/);
  assert.match(d.notes.join(' '), /earlier months of this year were not run in MyCA/);
  assert.ok(d.rulesUsed.includes('payroll.epf.wage-ceiling@2014-09-01'));
  assert.ok(d.rulesUsed.includes('payroll.pt.27@2023-04-01'));
  assert.equal(isRemoteQuery('payroll_run'), true);
  assert.equal(validateAssistantToolCall('payroll_run', { period: '2026-10' }).ok, true);
  assert.equal(validateAssistantToolCall('approve_payroll', { period: '2026-10', draftHash: 'x' }).ok, false);
});

test('approval posts salaries, payables and salary TDS, freezes the month, and payment clears salaries payable', async () => {
  const state = await books();
  const draft = (await runTool(state, 'payroll_run', { period: '2026-10' })).data;
  const preview = previewOf(state, 'approve_payroll', { period: '2026-10', draftHash: draft.draftHash });
  assert.deepEqual(preview.blockers, []);
  assert.match(preview.summary, /^Payroll for October 2026: 3 employees, gross ₹1,89,290\.32/);
  assert.match(preview.effects[0], /Pays nothing/);
  const approved = await runTool(state, 'approve_payroll', { period: '2026-10', draftHash: draft.draftHash });
  assert.equal(approved.ok, true, JSON.stringify(approved));
  assert.equal(trialBalance(state.ledger).balanced, true);
  const t = draft.totals;
  assert.equal(acc(state, '5120').debitsPosted, t.gross);
  assert.equal(balance(state, '2300'), t.net);
  assert.equal(balance(state, '2310'), t.pfPayable);
  assert.equal(balance(state, '2320'), t.esiPayable);
  assert.equal(balance(state, '2330'), t.pt);
  assert.equal(balance(state, '2200'), t.tds);
  assert.equal(acc(state, '5125').debitsPosted, t.employerContributions);
  const salaryTds = state.tdsEntries.filter((entry) => entry.section === '192');
  assert.equal(salaryTds.length, 1);
  assert.equal(salaryTds[0].payee, 'Arjun Rao');
  assert.equal(salaryTds[0].tds, t.tds);
  assert.equal((await runTool(state, 'tds_summary', {})).data.deducted, t.tds, 'salary TDS counts towards what is to deposit');
  const nonSalary = await runTool(state, 'tds_return', { quarter: 'Q3 2026-27' });
  assert.equal(nonSalary.ok, true, JSON.stringify(nonSalary));
  assert.equal(nonSalary.data.empty, true, 'but not in the non-salary statement');
  assert.equal(state.company.pf, true, 'PF deadlines switch on');
  const again = await runTool(state, 'payroll_run', { period: '2026-10' });
  assert.equal(again.data.status, 'approved');
  assert.equal(again.data.frozen, true);
  assert.equal(again.data.totals.net, t.net);
  assert.equal((await runTool(state, 'approve_payroll', { period: '2026-10' })).error, 'ALREADY_APPROVED');
  await runTool(state, 'change_salary', { id: 'EMP-0001', effectiveFrom: '2026-10-01', components: [{ name: 'Basic', amount: 50000 }] });
  assert.equal((await runTool(state, 'payroll_run', { period: '2026-10' })).data.totals.net, t.net, 'an approved month does not change');
  const list = await runTool(state, 'list_payroll', {});
  assert.equal(list.data.runs[0].paidOn, '');
  const early = await runTool(state, 'record_salary_payment', { period: '2026-10', date: '2026-09-30' });
  assert.equal(early.error, 'BEFORE_PERIOD');
  const paid = await runTool(state, 'record_salary_payment', { period: '2026-10', date: '2026-10-10' });
  assert.equal(paid.ok, true, JSON.stringify(paid));
  assert.equal(balance(state, '2300'), 0);
  assert.equal(acc(state, '1002').creditsPosted, t.net);
  assert.equal((await runTool(state, 'record_salary_payment', { period: '2026-10' })).error, 'ALREADY_PAID');
  const slip = await runTool(state, 'payslip', { period: '2026-10', employeeId: 'EMP-0003' });
  assert.equal(slip.ok, true, JSON.stringify(slip));
  assert.equal(slip.data.employee.name, 'Arjun Rao');
  assert.equal(slip.data.net, 150000 - 200 - t.tds);
  assert.deepEqual(slip.data.deductions.map((item) => item.name), ['Professional tax', 'Income tax (TDS)']);
  assert.equal(slip.data.paidOn, '2026-10-10');
  const copy = deserialize(JSON.parse(JSON.stringify(serialize(state))));
  assert.equal((await runTool(copy, 'payroll_run', { period: '2026-10' })).data.frozen, true);
  const november = (await runTool(state, 'payroll_run', { period: '2026-11' })).data;
  const arjunNov = november.rows.find((row) => row.name === 'Arjun Rao');
  assert.equal(arjunNov.tdsBasis.projectedSalary, 1800000);
  assert.equal(arjunNov.tds, Math.round((arjunNov.tdsBasis.annualTax - t.tds) / 5), 'what was deducted in October is taken off and the rest spread over five months');
});

test('only the owner runs payroll; chat runs, approves, records payment and shows a payslip', async () => {
  const root = await books();
  const staff = bookView(root, root, { actor: { userId: 'u-staff', role: 'staff' } });
  assert.equal((await runTool(staff, 'payroll_run', { period: '2026-10' })).error, 'SALARIES_PRIVATE');
  assert.match(previewOf(staff, 'approve_payroll', { period: '2026-10' }).blockers[0], /Only the owner/);
  const run = await chat(root, 'run payroll for October 2026');
  assert.match(run.reply, /^Payroll for October 2026: 3 employees, gross ₹1,89,290\.32/, run.reply);
  assert.match(run.reply, /Nothing is posted until you approve it\./);
  const held = await chat(root, 'approve payroll for October 2026');
  assert.equal(held.preview?.tool, 'approve_payroll', held.reply);
  assert.equal(Object.keys(root.payrollRuns).length, 0, 'nothing before yes');
  const done = await chat(root, 'yes');
  assert.match(done.reply, /^Approved payroll for October 2026: ₹1,89,290\.32 gross/);
  const paid = await chat(root, 'paid salaries for October 2026 on 2026-10-10');
  assert.equal(paid.preview?.tool, 'record_salary_payment', paid.reply);
  assert.match((await chat(root, 'yes')).reply, /^Recorded ₹[\d,]+\.\d\d of salaries for October 2026 paid from the bank on 10 October 2026\./);
  assert.match((await chat(root, 'payslip for EMP-0001 for October 2026')).reply, /^Payslip for Ravi Kumar, October 2026: gross ₹30,000\.00, deductions ₹2,000\.00, net ₹28,000\.00, paid on 10 October 2026./);
  assert.match((await chat(root, 'payroll months')).reply, /October 2026: 3 employees/);
});
