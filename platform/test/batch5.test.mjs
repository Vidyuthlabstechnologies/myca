import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createState, serialize, deserialize } from '../src/store.mjs';
import { runTool } from '../src/tools.mjs';
import { chat } from '../src/router.mjs';
import { listAccounts, trialBalance } from '../src/ledger.mjs';

const acc = (state, code) => listAccounts(state.ledger).find((a) => a.code === code);

test('closing a year moves income and expenses to capital, locks the books, and refuses a year not ended or already closed', async () => {
  const state = createState();
  state.company = { ...state.company, name: 'Asha Traders', gstin: '27AABCU9603R1ZN', state: '27' };
  await runTool(state, 'create_invoice', { partyName: 'Kiran Stores', lines: [{ description: 'Consulting', hsn: '9983', qty: 1, rate: 100000, gstRate: 18 }], date: '2025-06-05' });
  await runTool(state, 'post_expense', { narration: 'Shop rent', payee: 'Realty', amount: 20000, date: '2025-07-01' });
  await runTool(state, 'create_invoice', { partyName: 'Kiran Stores', lines: [{ description: 'Consulting', hsn: '9983', qty: 1, rate: 50000, gstRate: 18 }], date: '2026-05-05' });
  assert.equal((await runTool(state, 'close_year', { year: '2026-27' })).error, 'YEAR_NOT_ENDED');
  const out = await runTool(state, 'close_year', { year: '2025-26' });
  assert.equal(out.ok, true, JSON.stringify(out));
  const c = out.closing;
  assert.equal(c.income, 100000);
  assert.equal(c.expenses, 20000);
  assert.equal(c.profit, 80000);
  assert.equal(c.to, '2026-03-31');
  assert.equal(acc(state, '3000').creditsPosted, 100000);
  assert.equal(acc(state, '3000').debitsPosted, 20000);
  assert.equal(trialBalance(state.ledger).balanced, true);
  assert.equal(state.lockThrough, '2026-03-31');
  assert.equal((await runTool(state, 'close_year', { year: '2025-26' })).error, 'ALREADY_CLOSED');
  assert.equal((await runTool(state, 'post_expense', { narration: 'Late entry', payee: 'X', amount: 10, date: '2026-03-15' })).error, 'PERIOD_LOCKED');
  const list = await runTool(state, 'list_year_closings', {});
  assert.equal(list.data.closings[0].year, '2025-26');
  assert.equal(list.data.nextYear, '2025-26');
  const copy = deserialize(JSON.parse(JSON.stringify(serialize(state))));
  assert.equal(copy.yearClosings['2025-26'].profit, 80000);
  const us = createState();
  us.company = { name: 'Maple Street Bakery', country: 'US', gstin: '', state: '' };
  await runTool(us, 'set_sales_tax_rate', { code: 'TX', ratePercent: 6.25, from: '2025-01-01' });
  await runTool(us, 'create_invoice', { partyName: 'Cafe Luna', lines: [{ description: 'Cake', qty: 1, rate: 1000 }], date: '2025-03-01', taxJurisdiction: 'TX' });
  const usClose = await runTool(us, 'close_year', { year: '2025' });
  assert.equal(usClose.ok, true, JSON.stringify(usClose));
  assert.equal(usClose.closing.income, 1000);
  assert.equal(usClose.closing.to, '2025-12-31');
});

test('the week ahead lists filings, reminders, overdue invoices and unpaid payroll, and chat answers "what is due this week"', async () => {
  const state = createState();
  state.company = { ...state.company, name: 'Asha Traders', gstin: '27AABCU9603R1ZN', state: '27' };
  await runTool(state, 'create_invoice', { partyName: 'Kiran Stores', lines: [{ description: 'Consulting', hsn: '9983', qty: 1, rate: 10000, gstRate: 18 }], date: '2026-09-01', paymentTermsDays: 30 });
  await runTool(state, 'add_reminder', { text: 'Call Kiran about the cheque', due: '2026-10-14' });
  await runTool(state, 'add_employee', { name: 'Ravi Kumar', joinedOn: '2026-04-01', components: [{ name: 'Basic', amount: 20000 }], ptState: '27', sex: 'male' });
  const out = await runTool(state, 'week_ahead', { asOf: '2026-10-13' });
  assert.equal(out.ok, true, JSON.stringify(out));
  const kinds = out.data.items.map((item) => item.kind);
  assert.ok(kinds.includes('filing'), JSON.stringify(kinds));
  assert.ok(kinds.includes('reminder'));
  assert.ok(kinds.includes('receivable'));
  assert.ok(kinds.includes('payroll'));
  const receivable = out.data.items.find((item) => item.kind === 'receivable');
  assert.equal(receivable.overdue, true);
  assert.equal(receivable.amount, 11800);
  assert.ok(out.data.overdue >= 2);
  const reply = await chat(state, "what's due this week?");
  assert.match(reply.reply, /things in the week to/);
  assert.match(reply.reply, /Kiran Stores owes ₹11,800\.00 on INV-0001/);
  assert.match(reply.reply, /Call Kiran about the cheque/);
});

test('a QRMP business gets a quarterly GSTR-1 file and an IFF for the first two months; a monthly filer is told so', async () => {
  const state = createState();
  state.company = { ...state.company, name: 'Asha Traders', gstin: '27AABCU9603R1ZN', state: '27', gstFrequency: 'quarterly' };
  await runTool(state, 'create_invoice', { partyName: 'Kiran Stores', partyGstin: '27AAACK1234F1Z5', lines: [{ description: 'Consulting', hsn: '9983', qty: 1, rate: 10000, gstRate: 18 }], date: '2026-07-10' });
  await runTool(state, 'create_invoice', { partyName: 'Walk-in', lines: [{ description: 'Cloth', hsn: '5208', qty: 1, rate: 2000, gstRate: 5 }], date: '2026-08-10' });
  await runTool(state, 'create_invoice', { partyName: 'Kiran Stores', partyGstin: '27AAACK1234F1Z5', lines: [{ description: 'Consulting', hsn: '9983', qty: 1, rate: 30000, gstRate: 18 }], date: '2026-09-10' });
  const quarter = await runTool(state, 'export_gstr1_quarter', { quarter: 'Q2 2026-27' });
  assert.equal(quarter.ok, true, JSON.stringify(quarter).slice(0, 300));
  assert.equal(quarter.data.invoices, 3);
  assert.equal(quarter.data.fp, '092026');
  assert.equal(quarter.data.b2cs.length, 1);
  assert.deepEqual(quarter.data.iffMonths, [{ month: '2026-07', b2b: 1 }, { month: '2026-08', b2b: 0 }]);
  assert.equal(quarter.data.fileName, 'GSTR1_27AABCU9603R1ZN_Q2-2026-27.json');
  const iff = await runTool(state, 'export_iff', { period: '2026-07' });
  assert.equal(iff.ok, true, JSON.stringify(iff).slice(0, 300));
  assert.equal(iff.data.invoices, 1);
  assert.deepEqual(iff.data.b2cs, []);
  assert.equal((await runTool(state, 'export_iff', { period: '2026-09' })).error, 'QUARTER_END');
  const reply = await chat(state, 'quarterly GSTR-1 for Q2 2026-27');
  assert.match(reply.reply, /Quarterly GSTR-1 for Q2 2026-27: 3 invoices over July 2026, August 2026, September 2026/);
  const monthly = createState();
  monthly.company = { ...monthly.company, gstin: '27AABCU9603R1ZN', state: '27' };
  assert.equal((await runTool(monthly, 'export_gstr1_quarter', { quarter: 'Q2 2026-27' })).error, 'NOT_QRMP');
});

test('US quotes carry sales tax by jurisdiction and convert to invoices; a credit note on a US invoice reverses the sales tax', async () => {
  const state = createState();
  state.company = { name: 'Maple Street Bakery', country: 'US', gstin: '', state: '', address: '12 Maple St' };
  await runTool(state, 'set_sales_tax_rate', { code: 'TX', ratePercent: 6.25, from: '2026-01-01' });
  assert.equal((await runTool(state, 'create_quote', { partyName: 'Cafe Luna', lines: [{ description: 'Cake', qty: 2, rate: 100 }] })).error, 'JURISDICTION_REQUIRED');
  const quote = await runTool(state, 'create_quote', { partyName: 'Cafe Luna', lines: [{ description: 'Cake', qty: 2, rate: 100 }, { description: 'Delivery', qty: 1, rate: 20, taxable: false }], taxJurisdiction: 'tx', validDays: 15 });
  assert.equal(quote.ok, true, JSON.stringify(quote));
  assert.equal(quote.quote.country, 'US');
  assert.equal(quote.quote.subtotal, 220);
  assert.equal(quote.quote.salesTax, 12.5);
  assert.equal(quote.quote.total, 232.5);
  const converted = await runTool(state, 'convert_quote', { id: quote.quote.id, date: '2026-10-10' });
  assert.equal(converted.ok, true, JSON.stringify(converted));
  const invoice = converted.invoice;
  assert.equal(invoice.country, 'US');
  assert.equal(invoice.salesTax, 12.5);
  assert.equal(invoice.total, 232.5);
  const exempt = await runTool(state, 'create_quote', { partyName: 'Church', lines: [{ description: 'Cookies', qty: 10, rate: 2 }], taxExempt: true, exemptionReason: 'Resale certificate' });
  assert.equal(exempt.quote.salesTax, 0);
  const note = await runTool(state, 'create_credit_note', { invoiceId: invoice.id, amount: 116.25, reason: 'Half the order returned', date: '2026-10-12' });
  assert.equal(note.ok, true, JSON.stringify(note));
  assert.equal(note.creditNote.country, 'US');
  assert.equal(note.creditNote.salesTax, 6.25);
  assert.equal(note.creditNote.total, 116.25);
  assert.equal(acc(state, '2110').debitsPosted, 6.25);
  assert.equal(acc(state, '4000').debitsPosted, 110);
  assert.equal(trialBalance(state.ledger).balanced, true);
  const ret = await runTool(state, 'set_sales_tax_nexus', { state: 'TX', frequency: 'monthly', from: '2026-10-01' });
  assert.equal(ret.ok, true);
});
