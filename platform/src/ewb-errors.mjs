function codesOf(value) {
  return String(value ?? '').split(',').map((code) => code.trim()).filter(Boolean);
}

export function ewbErrorWords(code) {
  return EWB_WORDS[Number(code)] || '';
}

export function ewbRefusal(inner) {
  if (!inner || typeof inner !== 'object') return null;
  if (String(inner.status ?? '') === '0') {
    const codes = codesOf(inner.error?.errorCodes ?? inner.error?.error_cd);
    const words = codes.map(ewbErrorWords).filter(Boolean);
    return {
      error: codes.length ? `EWB_${codes[0]}` : 'EWB_REFUSED',
      codes,
      message: words.join(' ') || String(inner.error?.message || inner.info || ''),
    };
  }
  if (Object.hasOwn(inner, 'Status') && Number(inner.Status) === 0) {
    const first = Array.isArray(inner.ErrorDetails) ? inner.ErrorDetails[0] : null;
    const code = String(first?.ErrorCode || '').trim();
    return {
      error: code ? `IRP_${code}` : 'IRP_REFUSED',
      codes: code ? [code] : [],
      message: String(first?.ErrorMessage || '') || ewbErrorWords(code),
    };
  }
  return null;
}
